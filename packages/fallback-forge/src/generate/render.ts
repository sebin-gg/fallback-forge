import type {
  Block,
  EssentialAction,
  FormField,
  GenerateFlag,
  InspectedForm,
  LinkItem,
  Outline,
} from '../types.js';
import { companionPath, normalizeRoute } from '../config.js';

export interface RenderContext {
  siteName: string;
  companionBase: string;
  /** Routes that have a companion page; internal links to them are rewritten. */
  routes: string[];
  actions: EssentialAction[];
  storageKey: string;
  queryParam: string;
}

interface RenderState {
  route: string;
  ctx: RenderContext;
  flags: GenerateFlag[];
}

