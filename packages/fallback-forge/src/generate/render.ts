/** Remember the manual choice so the detector stops redirecting, then go to the full page. */
export function fullVersionScript(storageKey: string): string {
  return (
    "document.querySelectorAll('a[data-ff-full]').forEach(function(a){a.addEventListener('click',function(){" +
    `try{localStorage.setItem(${JSON.stringify(storageKey)},'full')}catch(e){}})});`
  );
}

export function renderPage(
  outline: Outline,
  ctx: RenderContext,
): { html: string; flags: GenerateFlag[] } {
  const state: RenderState = { route: outline.route, ctx, flags: [] };
  const body = outline.blocks.map((b) => renderBlock(b, state)).join('\n');
  const hasForm = outline.blocks.some((b) => b.kind === 'form');
  const fullHref = `${outline.route}?${ctx.queryParam}=0`;
  const html = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>${esc(outline.title)} · ${esc(ctx.siteName)} (lightweight)</title>
<meta name="robots" content="noindex">
<link rel="canonical" href="${esc(outline.route)}">
<style>${LITE_CSS}</style>
</head>
<body>
<p class="ff-banner">Lightweight version for slow connections. <a href="${esc(fullHref)}" data-ff-full>Use the full site</a></p>
<main>
${body}
</main>
<footer>Generated by Fallback Forge · <a href="${esc(fullHref)}" data-ff-full>Full version</a></footer>
<script>${fullVersionScript(ctx.storageKey)}${hasForm ? FORM_SCRIPT : ''}</script>
</body>
</html>
`;
  return { html, flags: state.flags };
}

const RENDERERS: Record<Block['kind'], (b: Block, s: RenderState) => string> = {
  heading: (b) => (b.kind === 'heading' ? `<h${b.level}>${esc(b.text)}</h${b.level}>` : ''),
  paragraph: (b) => (b.kind === 'paragraph' ? `<p>${esc(b.text)}</p>` : ''),
  list: (b, s) => (b.kind === 'list' ? renderList(b, s.ctx) : ''),
  definitions: (b) =>
    b.kind === 'definitions'
      ? `<dl>${b.items.map((i) => `<dt>${esc(i.term)}</dt><dd>${esc(i.detail)}</dd>`).join('')}</dl>`
      : '',
  table: (b) => (b.kind === 'table' ? renderTable(b.rows) : ''),
  nav: (b, s) =>
    b.kind === 'nav'
      ? `<nav aria-label="Main">${b.links.map((l) => link(l, s.ctx)).join(' ')}</nav>`
      : '',
  link: (b, s) => (b.kind === 'link' ? `<p>${link(b.link, s.ctx)}</p>` : ''),
  form: (b, s) => (b.kind === 'form' ? renderForm(b.form, s) : ''),
  image: () => '',
  widget: () => '',
};

function renderBlock(block: Block, state: RenderState): string {
  return RENDERERS[block.kind](block, state);
}

function renderList(block: Extract<Block, { kind: 'list' }>, ctx: RenderContext): string {
  const tag = block.ordered ? 'ol' : 'ul';
  const items = block.items.map((i) => {
    const inner = i.href
      ? link({ text: i.text, href: i.href, internal: i.href.startsWith('/') }, ctx)
      : esc(i.text);
    return `<li>${inner}</li>`;
  });
  return `<${tag}>${items.join('')}</${tag}>`;
}

function renderTable(rows: string[][]): string {
  const tr = rows.map((r, idx) => {
    const cell = idx === 0 ? 'th' : 'td';
    return `<tr>${r.map((c) => `<${cell}>${esc(c)}</${cell}>`).join('')}</tr>`;
  });
  return `<table>${tr.join('')}</table>`;
}

function link(l: LinkItem, ctx: RenderContext): string {
  return `<a href="${esc(rewriteHref(l.href, ctx))}">${esc(l.text)}</a>`;
}

/** Internal links to routes that have a companion page stay inside the lightweight version. */
export function rewriteHref(href: string, ctx: RenderContext): string {
  if (!href.startsWith('/') || href.startsWith('//')) return href;
  const [pathPart, rest] = splitHref(href);
  const route = normalizeRoute(pathPart);
  return ctx.routes.includes(route) ? companionPath(ctx.companionBase, route) + rest : href;
}

function splitHref(href: string): [string, string] {
  const m = /^([^?#]*)(.*)$/.exec(href);
  return [m?.[1] ?? href, m?.[2] ?? ''];
}

/** Endpoint comes from the developer-approved form action for this route, else the form's own `action`. */
function resolveEndpoint(
  form: InspectedForm,
  state: RenderState,
): { endpoint?: string; method: string } {
  const action = state.ctx.actions.find((a) => a.type === 'form' && a.route === state.route);
  const declared = action?.endpoint;
  const endpoint = declared && !declared.startsWith('TODO') ? declared : form.action;
  const fallbackMethod = form.method === 'GET' ? 'POST' : form.method;
  return { endpoint, method: (action?.method ?? fallbackMethod).toUpperCase() };
}

function renderForm(form: InspectedForm, state: RenderState): string {
  const { endpoint, method } = resolveEndpoint(form, state);
  const id = form.id ? ` id="${esc(form.id)}"` : '';
  const fields = form.fields.map(renderField).join('\n');
  if (!endpoint) return renderUnavailableForm(form, id, fields, state);
  return `<form${id} action="${esc(endpoint)}" method="${esc(method)}" data-ff>
${fields}
<button type="submit">${esc(form.submitText)}</button>
<p class="ff-out" role="status" aria-live="polite"></p>
</form>`;
}

function renderUnavailableForm(
  form: InspectedForm,
  id: string,
  fields: string,
  state: RenderState,
): string {
  const name = form.id ? ` "${form.id}"` : '';
  state.flags.push({
    route: state.route,
    severity: 'error',
    message: `Form${name} on ${state.route} has no resolvable endpoint; submission is unavailable in the lightweight version. Declare a \`form\` essential action with \`endpoint\`.`,
  });
  const fullHref = `${state.route}?${state.ctx.queryParam}=0`;
  return `<form${id}>\n${fields}\n<p class="ff-note">This form cannot be submitted in the lightweight version. <a href="${esc(fullHref)}" data-ff-full>Open the full site</a> to submit it.</p>\n</form>`;
}

const FIELD_RENDERERS: Record<string, (f: FormField, label: string, req: string) => string> = {
  textarea: (f, label, req) =>
    `<label>${label}<textarea name="${esc(f.name)}"${req}${attr('placeholder', f.placeholder)}></textarea></label>`,
  select: (f, label, req) => {
    const opts = (f.options ?? [])
      .map((o) => `<option value="${esc(o.value)}">${esc(o.label)}</option>`)
      .join('');
    return `<label>${label}<select name="${esc(f.name)}"${req}>${opts}</select></label>`;
  },
  checkbox: (f, label, req) =>
    `<label><input type="checkbox" name="${esc(f.name)}"${req}> ${label}</label>`,
  radio: (f, label, req) =>
    `<label><input type="radio" name="${esc(f.name)}"${req}> ${label}</label>`,
};

function renderField(f: FormField): string {
  const req = f.required ? ' required' : '';
  const label = esc(f.label || f.name);
  const special = FIELD_RENDERERS[f.type];
  if (special) return special(f, label, req);
  return `<label>${label}<input type="${esc(f.type)}" name="${esc(f.name)}"${req}${attr('placeholder', f.placeholder)}></label>`;
}

function attr(name: string, value?: string): string {
  return value ? ` ${name}="${esc(value)}"` : '';
}

export function esc(s: string): string {
  return s
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}
